#!/usr/bin/env python3
"""Generates the compliance-framework templates and their documentation from frameworks/*.yaml.

The YAML files are the single source of truth: each one holds a framework, its controls, how every control is matched to
scanner findings, and why. From them this script writes
  charts/rampart-policies/templates/compliance/<id>.yaml   the Helm template (what the cluster gets)
  docs/frameworks/<id>.md                                  how the framework was written, control by control
  rendered/cluster/<id>.yaml                               the same resource as a plain, readable ClusterComplianceFramework
  docs/frameworks/README.md                                the index
so the explanation can never differ from what is installed. `--check` writes nothing and fails if a file is out of date
(CI runs it). Usage: scripts/generate.py [--check]
"""
import json
import pathlib
import re
import sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "frameworks"
TPL = ROOT / "charts/rampart-policies/templates/compliance"
DOC = ROOT / "docs/frameworks"
RND = ROOT / "rendered/cluster"
CWE = json.loads((SRC / "cwe-names.json").read_text())
LOGOS = ROOT / "logos"
LOGO_BASE = yaml.safe_load((ROOT / "charts/rampart-policies/values.yaml").read_text())["compliance"]["logoBaseUrl"].rstrip("/")
SEVERITIES = ("critical", "high", "medium", "low")
CATEGORIES = ("sast", "sca", "secret", "iac", "container", "dast", "cspm", "compliance", "license", "supply_chain")
LEVELS = {
    "primary": "Identifiers and titles were read from the publisher's own text or machine-readable data.",
    "secondary": "Identifiers and titles come from published guidance and summaries, because the standard itself is not freely available. Check them against the standard before an audit.",
}


def logo_url(f):
    return f"{LOGO_BASE}/{f['id']}.svg"


def fail(msg):
    sys.exit(f"generate.py: {msg}")


def j(v):
    return json.dumps(v, ensure_ascii=False)


def resource_control(c):
    out = {"id": c["id"], "name": c["name"]}
    if c.get("manual"):
        out["manual"] = True
    else:
        m = {}
        for k in ("cwes", "categories", "minSeverity"):
            if c.get(k):
                m[k] = c[k]
        out["match"] = m
        if c.get("evidence"):
            out["evidence"] = {"categories": c["evidence"]}
    if c.get("description"):
        out["description"] = c["description"]
    return out


def validate(f, name):
    for k in ("key", "id", "scope", "displayName", "version", "source", "description", "note", "evidenceWindowDays", "verification", "controls"):
        if k not in f:
            fail(f"{name}: missing {k}")
    if f["verification"]["level"] not in LEVELS:
        fail(f"{name}: verification.level must be primary or secondary")
    if not (LOGOS / f"{f['id']}.svg").exists():
        fail(f"{name}: no logos/{f['id']}.svg: run scripts/marks.py <a Rampart checkout>")
    seen = set()
    for c in f["controls"]:
        for k in ("id", "name", "why"):
            if not c.get(k):
                fail(f"{name}: a control lacks {k}: {c}")
        if c["id"] in seen:
            fail(f"{name}: duplicate control id {c['id']}")
        seen.add(c["id"])
        has_match = any(c.get(k) for k in ("cwes", "categories"))
        if bool(c.get("manual")) == has_match:
            fail(f"{name}/{c['id']}: a control is either manual or matched by cwes/categories, not both and not neither")
        if c.get("minSeverity") and c["minSeverity"] not in SEVERITIES:
            fail(f"{name}/{c['id']}: bad minSeverity")
        for cat in (c.get("categories") or []) + (c.get("evidence") or []):
            if cat not in CATEGORIES:
                fail(f"{name}/{c['id']}: unknown category {cat}")
        for cwe in c.get("cwes") or []:
            if str(cwe) not in CWE:
                fail(f"{name}/{c['id']}: CWE-{cwe} has no name in frameworks/cwe-names.json")
        if "{{" in json.dumps(c):
            fail(f"{name}/{c['id']}: '{{{{' would be read by Helm")


def template(f, src):
    lines = [
        f"{{{{- /* GENERATED by scripts/generate.py from frameworks/{src}. Do not edit this file: edit the source and run the script. */ -}}}}",
        f"{{{{- if .Values.compliance.{f['key']}.enabled }}}}",
        "---",
        "apiVersion: rampart.aspm.dev/v1alpha1",
        'kind: {{ include "rampart-policies.kind" (dict "ctx" . "kind" "ComplianceFramework") }}',
        "metadata:",
        f'  {{{{- include "rampart-policies.meta" (dict "ctx" . "name" "{f["id"]}") | nindent 2 }}}}',
        "spec:",
        f"  displayName: {j(f['displayName'])}",
        f"  version: {j(f['version'])}",
        f"  source: {j(f['source'])}",
        f'  {{{{- $logo := index (.Values.compliance.logoUrls | default dict) "{f["key"]}" }}}}',
        "  {{- if and (not $logo) .Values.compliance.logos }}",
        f'  {{{{- $logo = printf "%s/%s.svg" (.Values.compliance.logoBaseUrl | trimSuffix "/") "{f["id"]}" }}}}',
        "  {{- end }}",
        "  {{- if $logo }}",
        "  logoUrl: {{ $logo | quote }}",
        "  {{- end }}",
        f"  description: {j(f['description'])}",
        f"  note: {j(f['note'])}",
        f"  appliesTo: {{complianceScope: {f['scope']}}}",
        f"  evidenceWindowDays: {int(f['evidenceWindowDays'])}",
        "  controls:",
    ]
    lines += [f"    - {j(resource_control(c))}" for c in f["controls"]]
    lines.append("{{- end }}")
    return "\n".join(lines) + "\n"


def plain_resource(f, src):
    """The resource the chart creates (cluster scope) as ordinary YAML, so it can be read and applied by hand."""
    spec = {
        "displayName": f["displayName"],
        "version": f["version"],
        "source": f["source"],
        "logoUrl": logo_url(f),
        "description": f["description"],
        "note": f["note"],
        "appliesTo": {"complianceScope": f["scope"]},
        "evidenceWindowDays": int(f["evidenceWindowDays"]),
        "controls": [resource_control(c) for c in f["controls"]],
    }
    doc = {"apiVersion": "rampart.aspm.dev/v1alpha1", "kind": "ClusterComplianceFramework", "metadata": {"name": f["id"]}, "spec": spec}
    head = (
        f"# GENERATED by scripts/generate.py from frameworks/{src}. Do not edit: edit the source and run the script.\n"
        "# This is the resource the Helm chart creates when scope is cluster, written out as plain YAML so it can be read\n"
        f"# and applied by hand:   rampart apply -f rendered/cluster/{f['id']}.yaml\n"
        f"# How each control was chosen and mapped: docs/frameworks/{f['id']}.md\n"
    )
    return head + yaml.safe_dump(doc, sort_keys=False, allow_unicode=True, width=110, default_flow_style=False)


def how_matched(c):
    if c.get("manual"):
        return "**Manual.** A person attests it."
    parts = []
    if c.get("categories"):
        parts.append("open findings of kind " + ", ".join(f"`{x}`" for x in c["categories"]))
    if c.get("cwes"):
        parts.append("open findings with weakness " + ", ".join(f"CWE-{x}" for x in c["cwes"]))
    s = "Counts " + " or ".join(parts)
    if c.get("minSeverity"):
        s += f", severity **{c['minSeverity']}** or above"
    if c.get("evidence"):
        s += "; evidenced by a scan of kind " + ", ".join(f"`{x}`" for x in c["evidence"])
    elif c.get("cwes") and not c.get("categories"):
        s += "; evidenced by a code scan (`sast` or `dast`), the server's rule for weakness-only controls"
    return s + "."


def doc(f, src):
    v = f["verification"]
    n_manual = sum(1 for c in f["controls"] if c.get("manual"))
    out = [
        f"# {f['displayName']}",
        "",
        f"_Generated by `scripts/generate.py` from `frameworks/{src}`. Do not edit this file._",
        "",
        f["description"],
        "",
        "## Where it comes from",
        "",
        f"- **Resource:** `{f['id']}` (a `ComplianceFramework`), switched on with `compliance.{f['key']}.enabled`. It reads only applications that list `{f['scope']}` in `complianceScope`.",
        f"- **Version covered:** {f['version']}",
        f"- **Source:** <{f['source']}>",
        f"- **Logo:** <{logo_url(f)}>, a mark Rampart draws itself (a flat shape with the framework's letters), not the publisher's logo; see [../METHOD.md](../METHOD.md), \"Logos\".",
        f"- **Verification: {v['level']}.** {LEVELS[v['level']]}",
        f"  - How: {v['how']}",
    ]
    if f.get("licence"):
        out.append(f"- **Licence and wording:** {f['licence']}")
    out += [
        "",
        "## How it was written",
        "",
        "The general method is in [../METHOD.md](../METHOD.md): which controls are chosen, how a control is matched to scanner findings or left to a person, and what the severity floors and evidence windows mean. For this framework:",
        "",
    ]
    out += [f"- {x}" for x in f["decisions"]]
    out += [
        f"- Evidence window: **{f['evidenceWindowDays']} days.** {f.get('windowWhy', 'A scan older than this does not evidence a control.')}",
        f"- {len(f['controls'])} controls: {len(f['controls']) - n_manual} matched to scanner findings, {n_manual} manual.",
        "",
        "## Controls",
        "",
        "| Id | Control | How Rampart reads it | Why |",
        "|---|---|---|---|",
    ]
    for c in f["controls"]:
        out.append(f"| {c['id']} | {c['name']} | {how_matched(c)} | {c['why']} |")
    used = sorted({int(x) for c in f["controls"] for x in (c.get("cwes") or [])})
    if used:
        out += ["", "## Weaknesses used", "", "Names are MITRE's, from CWE catalogue 5.0 (2026-10-28).", "", "| CWE | Name |", "|---|---|"]
        out += [f"| CWE-{x} | {CWE[str(x)]} |" for x in used]
    out += ["", "## What it does not cover", ""]
    out += [f"- {x}" for x in f["limits"]]
    out += [
        "",
        "## How to read the result",
        "",
        "A matched control reads `clear` when a scan that could evidence it ran within the window and nothing it counts is open, `open` when something is open, and `not assessed` when no such scan ran. A manual control stays unassessed until a person attests it. A `clear` control means *no open finding of the kind the control watches*; it does not prove the requirement is met.",
        "",
    ]
    return "\n".join(out)


def index(fws):
    out = [
        "# Compliance frameworks",
        "",
        "_Generated by `scripts/generate.py`. Do not edit this file._",
        "",
        "Each framework below is written from a source file in `frameworks/`, and its page says where the identifiers come from, how every control is read, and why. How the frameworks are written in general is in [../METHOD.md](../METHOD.md). **Verification** says whether the identifiers were read from the publisher's own text (primary) or from published guidance because the standard is not freely available (secondary).",
        "",
        "| Framework | Scope | Controls | Matched | Manual | Verification | Window (days) |",
        "|---|---|---|---|---|---|---|",
    ]
    for f in fws:
        m = sum(1 for c in f["controls"] if c.get("manual"))
        out.append(f"| [{f['displayName']}]({f['id']}.md) | `{f['scope']}` | {len(f['controls'])} | {len(f['controls']) - m} | {m} | {f['verification']['level']} | {f['evidenceWindowDays']} |")
    return "\n".join(out) + "\n"


def when(iso):
    from datetime import datetime
    return datetime.fromisoformat(iso.replace("Z", "+00:00")).strftime("%Y-%m-%d %H:%M UTC")


def fill(path, blocks):
    """Replaces what is between <!-- generated:NAME --> and <!-- /generated:NAME --> in a hand-written page."""
    s = path.read_text()
    for name, text in blocks.items():
        a, b = f"<!-- generated:{name} -->", f"<!-- /generated:{name} -->"
        if a not in s or b not in s:
            fail(f"{path.name} has no generated:{name} block")
        i = s.index(a) + len(a)
        s = s[:i] + "\n" + text.strip("\n") + "\n" + s[s.index(b):]
    return s


def results_blocks(g):
    pol, bands = g["policy"], g["policy"]["bands"]
    limits = [("critical", bands["critical"]), ("high", bands["high"]), ("medium", bands["medium"])]
    f = ["| Factor | Group | Condition | Points | Reason |", "|---|---|---|---|---|"]
    for x in pol["factors"]:
        f.append(f"| `{x['name']}` | {x.get('group', '')} | `{x['when']}` | {x['points']:+d} | {x['reason']} |")
    b = [
        "| Band | From score |", "|---|---|",
        f"| critical | {bands['critical']} |", f"| high | {bands['high']} |", f"| medium | {bands['medium']} |", "| low | below " + str(bands["medium"]) + " |",
        "",
        "How many more points a finding needs, on top of its base, to reach each band:",
        "",
        "| Severity | Base | To medium | To high | To critical |", "|---|---|---|---|---|",
    ]
    for sev in ("critical", "high", "medium", "low", "info"):
        base = pol["base"][sev]
        cells = [("already" if base >= lim else f"+{lim - base}") for _, lim in reversed(limits)]
        b.append(f"| {sev} | {base} | " + " | ".join(cells) + " |")
    sc = ["| Example | What | Base | Factors that applied | Score | Band |", "|---|---|---|---|---|---|"]
    for r in g["scenarios"]:
        fac = ", ".join(f"`{x['name']}` {x['points']:+d}" for x in r["factors"]) or "none"
        sc.append(f"| **{r['id']}** | {r['title']}. {r['story']} | {r['base']} | {fac} | **{r['score']}** | {r['band']} |")
    prof = []
    for name, p in g["slaProfiles"].items():
        prof += [f"**`{name}`**: `maxDays` {p['maxDays']}, `kevDueDate` {'on' if p['kevDueDate'] else 'off'}, from {p['startFrom']}", "",
                 "| Band \\ criticality | critical | high | medium | low |", "|---|---|---|---|---|"]
        for band in ("critical", "high", "medium", "low"):
            row = p["matrix"][band]
            prof.append(f"| {band} | " + " | ".join(str(row[c]) for c in ("critical", "high", "medium", "low")) + " |")
        prof.append("")
    profs = list(g["slaProfiles"].keys())
    sl = ["| Example | Band, criticality | " + " | ".join(profs) + " | Due (rampart) |", "|---|---|" + "---|" * len(profs) + "---|"]
    for r in g["scenarios"]:
        d = r["days"]
        due = when(r["due"]) + (f" (capped by the CISA due date; without it {when(r['dueWithoutCap'])})" if r["cappedByKEV"] else "")
        sl.append(f"| **{r['id']}** | {r['band']}, {r['input']['app'].get('Criticality') or r['input']['app'].get('criticality', '')} | " + " | ".join(str(d[x]) for x in profs) + f" | {due} |")
    return {"factors": "\n".join(f), "bands": "\n".join(b), "scenarios": "\n".join(sc), "profiles": "\n".join(prof)}, "\n".join(sl)


def main():
    check = "--check" in sys.argv
    files = sorted(SRC.glob("*.yaml"))
    fws = []
    for p in files:
        f = yaml.safe_load(p.read_text())
        validate(f, p.name)
        f["_src"] = p.name
        fws.append(f)
    keys = [f["key"] for f in fws]
    if len(set(keys)) != len(keys) or len({f["id"] for f in fws}) != len(fws):
        fail("duplicate key or id")
    chart = ROOT / "charts/rampart-policies"
    for vf in [chart / "values.yaml", chart / "ci/cluster-all-values.yaml", chart / "ci/namespace-all-values.yaml"]:
        comp = (yaml.safe_load(vf.read_text()) or {}).get("compliance", {})
        for k in keys:
            if k not in comp:
                fail(f"{vf.relative_to(ROOT)} has no compliance.{k}")
        for k in comp:
            if k not in ("logos", "logoBaseUrl", "logoUrls") and k not in keys:
                fail(f"{vf.relative_to(ROOT)} has compliance.{k} but there is no framework for it")
    want = {}
    for f in fws:
        want[TPL / f"{f['id']}.yaml"] = template(f, f["_src"])
        want[DOC / f"{f['id']}.md"] = doc(f, f["_src"])
        want[RND / f"{f['id']}.yaml"] = plain_resource(f, f["_src"])
    want[DOC / "README.md"] = index(fws)
    golden = ROOT / "docs/scenarios.golden.json"
    if golden.exists():
        g = json.loads(golden.read_text())
        blocks, sla_rows = results_blocks(g)
        want[ROOT / "docs/SCORING.md"] = fill(ROOT / "docs/SCORING.md", {k: blocks[k] for k in ("factors", "bands", "scenarios")})
        want[ROOT / "docs/SLA.md"] = fill(ROOT / "docs/SLA.md", {"profiles": blocks["profiles"], "sla-scenarios": sla_rows})
    elif check:
        fail("docs/scenarios.golden.json is missing: run UPDATE_GOLDEN=1 scripts/check.sh <a Rampart checkout>")
    stale = []
    for path, text in want.items():
        if not path.exists() or path.read_text() != text:
            stale.append(path)
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text)
    for d in (TPL, DOC, RND):
        for p in d.glob("*"):
            if p not in want:
                stale.append(p)
                if not check:
                    p.unlink()
    if check and stale:
        fail("out of date, run scripts/generate.py: " + ", ".join(str(p.relative_to(ROOT)) for p in stale))
    print(("checked " if check else "wrote ") + f"{len(fws)} frameworks")


main()
